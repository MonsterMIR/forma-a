<?php
declare(strict_types=1);

/**
 * РАУНД 109 (21.10.2026) — исправление третьей по счёту ошибочной
 * автосвязки P4VVIP (после round106: #84/#97): рейсы #97/#98 и #108/#109
 * были автоматически связаны старым правилом (раунд 33/40/69, "любой
 * непривязанный рейс противоположного типа"), которое не проверяло
 * хронологический порядок (прилёт не может быть позже вылета в одной
 * паре "один визит").
 *
 * Разбор (по прямому указанию пользователя + расшифровка приложенного
 * разрешения CAA UZB 264/10/2026 TVT/SKD, переведено из UTC в местное
 * время +5ч):
 *   #98  вылет  20.10 17:30  (ETD UZTP 12:30Z)
 *   #97  прилёт 20.10 20:00  (ETA UZTP 15:00Z)
 *   #108 вылет  21.10 08:30  (ETD UZTP 03:30Z)
 *   #109 прилёт 21.10 16:15  (ETA UZTP 11:15Z)
 *
 * Единственная пара, где прилёт предшествует следующему вылету (значит,
 * это непрерывная стоянка одного визита) — #97 (прилетел 20:00 20.10) →
 * #108 (улетел 08:30 21.10), ночёвка ~12.5ч. Старая связка #97↔#98 и
 * #108↔#109 связывала КАЖДУЮ пару "вылет раньше своего прилёта" —
 * хронологически невозможно для одного визита, тот же класс ошибки, что
 * и в round106 (рейсы #84/#97).
 *
 * #98 и #109 остаются БЕЗ пары — это не баг, а правда данных: #98 это
 * вылет визита, прилёт которого в систему не внесён (пробел, как и у
 * рейса #84, round106); #109 это прилёт визита, который ещё не завершён
 * (вылет будет позже, его пока не существует). Оба корректно останутся
 * "сиротами" до появления настоящей пары — решение подтверждено
 * пользователем 21.10.2026.
 *
 * ПРОВЕРЕНО ПЕРЕД ЗАПУСКОМ (21.10.2026): пока шло обсуждение, ЦОК уже
 * создал и утвердил акт 0092/XX-P4VVIP (id=94) на рейс #108 — проверено,
 * что в нём НЕТ строк TLF/NIGHT/AV_SEC/OVER_PARK (только RAMP_25, LEAD,
 * BAG_DEP_PC, MET_50, PAX_DEP, PAX_SEC, SUPERV) — то есть он никак не
 * зависел от данных связанного рейса (#109 тоже без акта), и MTOW/стоянка
 * (22.00т / B-24R) у #97 и #108 УЖЕ совпадают один в один — релинк не
 * меняет ни одной цифры в уже утверждённом акте, только саму связь
 * flights.linked_flight_id. У #97/#98/#109 актов нет вообще.
 *
 * Безопасно запускать повторно.
 *
 * Запуск (по SSH, из корня public_html):
 *   php scripts/round109_relink_p4vvip_97_108.php
 */

define('BASE_PATH', dirname(__DIR__));

$envFile = BASE_PATH . '/.env';
if (file_exists($envFile)) {
    $lines = file($envFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    foreach ($lines as $line) {
        if (str_starts_with(trim($line), '#')) continue;
        if (!str_contains($line, '=')) continue;
        [$key, $value] = explode('=', $line, 2);
        $key   = trim($key);
        $value = trim($value, " \t\n\r\0\x0B\"'");
        $_ENV[$key] = $value;
        putenv("$key=$value");
    }
}

require BASE_PATH . '/vendor/autoload.php';

use App\Core\ActivityLogger;
use App\Models\Flight;
use App\Services\FlightService;

const F98  = 98;  // вылет 20.10 17:30 — должен остаться БЕЗ пары
const F97  = 97;  // прилёт 20.10 20:00
const F108 = 108; // вылет 21.10 08:30 — акт 0092/XX уже утверждён
const F109 = 109; // прилёт 21.10 16:15 — должен остаться БЕЗ пары

$flightModel = new Flight();
$service     = new FlightService();

$ids = [F98, F97, F108, F109];
$before = [];
foreach ($ids as $id) {
    $f = $flightModel->find($id);
    if (!$f) {
        fwrite(STDERR, "Рейс #{$id} не найден — прерываю.\n");
        exit(1);
    }
    $before[$id] = $f;
}

echo "До исправления:\n";
foreach ($ids as $id) {
    $f = $before[$id];
    echo "  #{$id} ({$f['operation_type']}, {$f['flight_date']} {$f['scheduled_time']}): linked_flight_id="
        . ($f['linked_flight_id'] ?: '—') . "\n";
}
echo "\n";

// Шаг 1: расцепляем обе ошибочные пары (если они ещё связаны именно так).
if ((int)($before[F97]['linked_flight_id'] ?? 0) === F98) {
    $r = $service->unlinkFlights(F97);
    echo "Шаг 1: #97 и #98 расцеплены — " . ($r['success'] ? 'OK' : ('ОШИБКА: ' . ($r['error'] ?? '?'))) . "\n";
} else {
    echo "Шаг 1: #97/#98 уже не связаны между собой — пропускаю.\n";
}

if ((int)($before[F108]['linked_flight_id'] ?? 0) === F109) {
    $r = $service->unlinkFlights(F108);
    echo "Шаг 1: #108 и #109 расцеплены — " . ($r['success'] ? 'OK' : ('ОШИБКА: ' . ($r['error'] ?? '?'))) . "\n";
} else {
    echo "Шаг 1: #108/#109 уже не связаны между собой — пропускаю.\n";
}

// Шаг 2: явная правильная связка #97 (прилёт 20:00 20.10) ↔ #108 (вылет
// 08:30 21.10) — подтверждена пользователем и расшифровкой разрешения.
$result = $service->linkFlights(F97, F108);
if (!$result['success']) {
    fwrite(STDERR, "Шаг 2: связка #97↔#108 не удалась — {$result['error']}\n");
    exit(1);
}
echo "Шаг 2: рейс #97 связан с рейсом #108 (подтверждённая правильная пара, ночёвка ~12.5ч).\n";

ActivityLogger::log(
    'flight', F97, 'manual_fix_link_permit_decoded', 'success',
    'Раунд 109: расцеплены ошибочные пары #97/#98 и #108/#109 (вылет раньше своего прилёта — '
        . 'хронологически невозможно для одного визита, тот же класс ошибки, что в round106). '
        . 'Связаны правильно #97 (прилёт 20:00 20.10) и #108 (вылет 08:30 21.10) — подтверждено '
        . 'расшифровкой разрешения CAA UZB 264/10/2026 TVT/SKD (UTC+5). #98 и #109 оставлены без '
        . 'пары — правда данных, не ошибка (их настоящие визиты не полностью внесены в систему).',
    null,
    ['linked' => [F97, F108], 'left_unpaired' => [F98, F109]]
);

echo "\nПосле исправления:\n";
foreach ($ids as $id) {
    $f = $flightModel->find($id);
    echo "  #{$id} ({$f['operation_type']}, {$f['flight_date']} {$f['scheduled_time']}): linked_flight_id="
        . ($f['linked_flight_id'] ?: '— (без пары, это ожидаемо)') . "\n";
}

echo "\nГотово. #98 и #109 намеренно остались без пары — их настоящие визиты (прилёт перед #98, "
    . "вылет после #109) в системе отсутствуют/ещё не наступили.\n";
