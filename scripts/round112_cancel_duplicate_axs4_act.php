<?php
declare(strict_types=1);

/**
 * РАУНД 112 (21.10.2026) — отмена дублирующего утверждённого акта
 * 0004/XX-AXS4 (рейс #13), найденного в round92 (16.10.2026) как реальный
 * задвоенный счёт из-за двойного клика по кнопке «Создать рейс» (05.10.2026,
 * рейсы #12 и #13 — идентичные, созданы с разницей в 3 секунды).
 *
 * По прямому указанию пользователя (21.10.2026): "Займись пока именно этим
 * делом" — после того, как ему было показано, что это реальные лишние
 * деньги в документах, в отличие от других предупреждений инвариантов.
 *
 * Разбор перед действием (см. claude/analysis round112 doc — полные цифры):
 *   - Рейс #2 (тот же борт T7POL, AXS4) — ПРОВЕРЕНО СЕГОДНЯ и НЕ является
 *     тем же событием: другое время (18:00 vs 15:00), другой MTOW (22.00 vs
 *     21.90), другая стоянка (B-4 vs B-24R), импортирован из разрешения
 *     30.09, и с 19.10.2026 имеет СВОЙ ОТДЕЛЬНЫЙ утверждённый акт
 *     (0057/XX-AXS4, $1904.00) — предположение round92 ("возможно, это и
 *     есть настоящий первоисточник") не подтвердилось, это отдельный
 *     реальный рейс. НЕ ТРОГАЕТСЯ этим раундом.
 *   - Рейсы #12 и #13 — настоящий дубль (идентичные данные, 3 секунды
 *     разницы). У КАЖДОГО свой манифест, и оба манифеста согласно
 *     показывают 6 пассажиров (не "6 против 1", как казалось по
 *     расхождению в самих актах — расхождение было только в акте, не в
 *     реальных данных о пассажирах).
 *   - Акт 0009/XX-AXS4 (рейс #12, $1831.00): PAX_SEC правильно
 *     авторассчитан на 6 пассажиров ($120) — содержание акта полностью
 *     верное.
 *   - Акт 0004/XX-AXS4 (рейс #13, $1731.00): PAX_SEC содержит ВРУЧНУЮ
 *     введённую строку на 1 пассажира ($20) вместо 6 ($120) — то есть этот
 *     акт не только дублирует акт 0009, но и сам по себе занижен на $100
 *     относительно реальных 6 пассажиров.
 *
 * Решение: оставить в силе акт 0009/XX-AXS4 (правильные суммы, включает
 * верный PAX_SEC на всех 6 пассажиров) как единственный официальный
 * документ по этому реальному вылету. Отменить (status='cancelled', а не
 * тихо удалить/изменить) акт 0004/XX-AXS4 через штатный, поддерживаемый
 * переход статуса approved → cancelled (ActService::changeStatus()) —
 * полностью видимый, обратимый в истории акта способ, никаких обходов
 * статус-гейтов не требуется (в отличие от round111 — там нужная
 * транзакция approved→draft в принципе не существует в системе, здесь же
 * 'cancelled' разрешён штатно).
 *
 * ВАЖНО: если один из этих актов уже был физически отправлен авиакомпании
 * T7POL/в бухгалтерию как окончательный документ — отмена в системе не
 * аннулирует бумажный/отправленный экземпляр автоматически; об этом нужно
 * сообщить пользователю отдельно (сделано в чате).
 *
 * Безопасно запускать повторно — если акт уже не 'approved', просто
 * сообщает об этом и ничего не делает (getAllowedTransitions не разрешит
 * переход, или скрипт сам проверит статус перед вызовом).
 *
 * Запуск (по SSH, из корня public_html):
 *   php scripts/round112_cancel_duplicate_axs4_act.php
 */

define('BASE_PATH', dirname(__DIR__));

$envFile = BASE_PATH . '/.env';
if (file_exists($envFile)) {
    foreach (file($envFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
        if (str_starts_with(trim($line), '#') || !str_contains($line, '=')) continue;
        [$k, $v] = explode('=', $line, 2);
        $k = trim($k); $v = trim($v, " \t\n\r\0\x0B\"'");
        $_ENV[$k] = $v; putenv("$k=$v");
    }
}
require BASE_PATH . '/vendor/autoload.php';

use App\Core\ActivityLogger;
use App\Models\Act;
use App\Models\Flight;
use App\Services\ActService;

const DUP_ACT_ID    = 4;  // 0004/XX-AXS4, рейс #13 — отменяется
const KEEP_ACT_ID   = 9;  // 0009/XX-AXS4, рейс #12 — остаётся в силе
const DUP_FLIGHT_ID = 13;

$actModel    = new Act();
$flightModel = new Flight();
$actService  = new ActService();

$dupAct  = $actModel->find(DUP_ACT_ID);
$keepAct = $actModel->find(KEEP_ACT_ID);

if (!$dupAct || !$keepAct) {
    fwrite(STDERR, "Один из актов не найден — прерываю.\n");
    exit(1);
}

echo "До отмены: акт {$dupAct['act_number']} (#" . DUP_ACT_ID . "), статус={$dupAct['status']}, сумма={$dupAct['total_amount_with_vat']}\n";
echo "Остаётся в силе: акт {$keepAct['act_number']} (#" . KEEP_ACT_ID . "), статус={$keepAct['status']}, сумма={$keepAct['total_amount_with_vat']}\n\n";

if ($dupAct['status'] !== 'approved') {
    echo "Акт {$dupAct['act_number']} уже не в статусе 'approved' (сейчас '{$dupAct['status']}') — пропускаю, ничего не делаю.\n";
    exit(0);
}

$reason = 'Round112: дубль акта 0009/XX-AXS4 (двойной клик 05.10.2026, см. round92) — отменён, '
    . 'реальный документ по этому вылету — 0009/XX-AXS4.';

$result = $actService->changeStatus(DUP_ACT_ID, 'cancelled', $reason);

if (!$result['success']) {
    fwrite(STDERR, "ОШИБКА при отмене акта: " . ($result['error'] ?? 'неизвестная ошибка') . "\n");
    exit(1);
}

echo "Акт {$dupAct['act_number']} переведён в статус 'cancelled'.\n";

// Видимая пометка на рейсе-дубле — для прозрачности при просмотре карточки рейса.
$flight = $flightModel->find(DUP_FLIGHT_ID);
if ($flight) {
    $noteAppend = "\n[Раунд 112, 21.10.2026] Этот рейс — дубль рейса #12 (двойной клик по «Создать рейс», "
        . "05.10.2026, см. round92). Акт 0004/XX-AXS4 по этому рейсу отменён (cancelled) — "
        . "действующий документ по этому реальному вылету: акт 0009/XX-AXS4 (рейс #12).";
    $flightModel->update(DUP_FLIGHT_ID, ['notes' => rtrim((string)($flight['notes'] ?? '')) . $noteAppend]);
    echo "Рейс #13: добавлена пояснительная пометка в notes.\n";
}

ActivityLogger::log(
    'act', DUP_ACT_ID, 'round112_cancel_duplicate_act', 'success',
    "Round112: акт 0004/XX-AXS4 (рейс #13) отменён как дубль утверждённого акта 0009/XX-AXS4 (рейс #12) — "
        . "двойной клик 05.10.2026 (round92). Дополнительно: сам акт 0004 содержал заниженный PAX_SEC "
        . "(1 пассажир вместо реальных 6 по обоим манифестам) — ещё одна причина, по которой он не является "
        . "корректным документом. Действующий документ: 0009/XX-AXS4 (\$1831.00, PAX_SEC верно на 6 пассажиров).",
    ['dup_act' => $dupAct],
    ['kept_act_id' => KEEP_ACT_ID, 'kept_act_number' => $keepAct['act_number']]
);

echo "\nГотово.\n";
